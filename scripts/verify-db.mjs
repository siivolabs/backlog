import { openDatabase, validateV1Contract, quickCheck, tableInfo } from '../src/db.js';
import { loadConfig } from '../src/config.js';
const config = loadConfig();
const db = openDatabase(config.databasePath, { readOnly: true });
validateV1Contract(db);
const check = quickCheck(db);
const counts = Object.fromEntries(['games','profiles','discovery_feedback','discovery_sessions'].map((table) => [table, db.prepare(`SELECT COUNT(*) AS n FROM ${table}`).get().n]));
console.log(JSON.stringify({ ok: check.ok, counts, gamesSchema: tableInfo(db, 'games') }, null, 2));
db.close();
if (!check.ok) process.exitCode = 1;
